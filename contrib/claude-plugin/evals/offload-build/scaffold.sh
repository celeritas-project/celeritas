# Geant4 example without offload, plus build-env.sh describing the host's
# Celeritas and Geant4 installations. Eval runs do not inherit the host
# environment, so the paths are resolved here from PATH.
CASE_DIR=$(cd "$(dirname "$0")" && pwd)
. "$CASE_DIR/../_lib/fixtures.sh"

for exe in celer-config geant4-config cmake; do
  if ! command -v "$exe" >/dev/null 2>&1; then
    echo "error: $exe is not on PATH: load Celeritas and Geant4 before" \
      "running the build tier" >&2
    exit 1
  fi
done

celer_prefix=$(cd "$(dirname "$(command -v celer-config)")/.." && pwd -P)
g4_prefix=$(cd "$(geant4-config --prefix)" && pwd -P)

# The eval's Bash sandbox cannot read the home directory, so CMake could not
# find an install there. HOME is a temporary directory in scaffolds, so look up
# the real one.
real_home=$(eval cd "~$(id -un)" && pwd -P)
for prefix in "$celer_prefix" "$g4_prefix"; do
  case "$prefix" in
    "$real_home" | "$real_home"/*)
      echo "error: $prefix is under $real_home, which the eval's Bash" \
        "sandbox cannot read: the build tier needs Celeritas and Geant4" \
        "installed outside the home directory" >&2
      exit 1
      ;;
  esac
done

copy_geant4_example_without_offload

{
  echo "# Generated by the eval scaffold: source before configuring"
  echo "export PATH=\"$PATH\""
  echo "export CMAKE_PREFIX_PATH=\"$celer_prefix:$g4_prefix\""
  echo "export CELER_DISABLE_PARALLEL=1"
  geant4-config --datasets | while read -r _name var path; do
    if [ -n "$var" ]; then
      echo "export $var=\"$path\""
    fi
  done
} > build-env.sh
